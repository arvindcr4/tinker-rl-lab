"""Regenerate the registry numbers quoted in the P6 (GRPO-Registry) paper from the live CLI.

Writes paper/sections/p6_registry_generated.tex, which defines
  \\STACKDIFFNPAIRS, \\STACKDIFFDIST, \\STACKDIFFUNDER, \\STACKDIFFCOVA, \\STACKDIFFCOVB
and the body of Table tab:p6-entries (\\input by p6_population.tex).

Run: python analysis_publication_fixes/p6_registry_numbers.py
"""

import collections
import argparse
import hashlib
import platform
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "registry"))
import query as q

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from analysis_validation import equivalence_classes, coverage_median


def main(output_dir):
    recs = q.load("stack")
    pairs = q.all_pairs(recs)
    lv = collections.Counter(r["level"] for r in pairs.values())
    und = sum(r["underspecified"] for r in pairs.values())
    dist = ", ".join(f"R{k}: {lv[k]}" for k in range(6))

    def ckpt(r):
        v = q.field_view(r)["checkpoint.id"]
        return q._key("checkpoint.id", v["value"]) if q.is_known(v) else None

    def lvdist(ps):
        c = collections.Counter(r["level"] for r in ps.values())
        return ", ".join(f"R{k} {c[k]}" for k in range(6) if c[k])

    same = {
        k: v for k, v in pairs.items() if ckpt(recs[k[0]]) and ckpt(recs[k[0]]) == ckpt(recs[k[1]])
    }
    # Candidate v2: exact normalized signatures, including missingness states.
    classes = equivalence_classes(recs, q)
    cls = {members[0]: members for members in classes}
    reps = {members[0]: recs[members[0]] for members in classes}
    dpairs = q.all_pairs(reps)
    dsame = {
        k: v for k, v in dpairs.items() if ckpt(reps[k[0]]) and ckpt(reps[k[0]]) == ckpt(reps[k[1]])
    }
    n_gen = sum(bool(r.get("run_config")) for r in recs.values())
    gpairs = q.all_pairs({k: r for k, r in recs.items() if r.get("run_config")})
    covs = sorted(r["coverage"] for r in pairs.values())
    a = q.stackdiff(recs["trl_grpo_qwen3-8b_gsm8k"], recs["tinker_grpo_qwen3-8b_gsm8k"])
    b = q.stackdiff(recs["colab-open_dapo_e3"], recs["tinker_dapo_qwen3.5-4b_gsm8k"])

    def esc(s):
        return str(s).replace("_", r"\_")

    def exec_mode(r):
        rid = r["id"]
        if rid.startswith("zvf130_"):
            return "fixture"
        mode = ((r.get("run_config") or {}).get("execution.mode") or {}).get("value")
        if mode == "dryrun":
            return "dry-run"
        n = len(r.get("seeds") or [])
        kind = "toy run" if rid.startswith("colab-open_") else "run"
        return f"{kind}, {n} seed" + ("s" if n != 1 else "")

    def show_model(m):
        # Display only: drop the org prefix and match the "-Base" casing that
        # stackdiff's case-insensitive normalizer already treats as equal.
        return str(m).split("/")[-1].replace("-base", "-Base")

    rows = []
    for rid in sorted(recs):
        r = recs[rid]
        total, _ = q.badge(r)
        mz = (r.get("outcomes") or {}).get("mean_zvf")
        model = (
            r.get("model")
            or (r.get("run_config") or {}).get("checkpoint.id", {}).get("value")
            or "--"
        )
        rows.append(
            f"{esc(rid)} & {esc(r['label_claimed'])} & {esc(r['framework']['openness'])} & "
            f"{esc(show_model(model))} & {exec_mode(r)} & {'--' if mz is None else f'{mz:.3f}'} & {total} & "
            f"{q.spec_coverage(r):.2f} \\\\"
        )
    out = output_dir / "p6_registry_generated_v2.tex"
    if out.exists() or (output_dir / "p6_registry_numbers_v2.json").exists():
        raise ValueError("refuse to overwrite candidate output")
    output_dir.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "% GENERATED by analysis_publication_fixes/p6_registry_numbers.py -- do not edit\n"
        f"\\newcommand{{\\STACKDIFFNPAIRS}}{{{len(pairs)}}}\n"
        f"\\newcommand{{\\STACKDIFFDIST}}{{{dist}}}\n"
        f"\\newcommand{{\\STACKDIFFUNDER}}{{{und}/{len(pairs)}}}\n"
        f"\\newcommand{{\\STACKDIFFCOVA}}{{{a['coverage']:.2f}}}\n"
        f"\\newcommand{{\\STACKDIFFCOVB}}{{{b['coverage']:.2f}}}\n"
        f"\\newcommand{{\\NSTACK}}{{{len(recs)}}}\n"
        f"\\newcommand{{\\NFIELDS}}{{{len(q.FIELDS)}}}\n"
        f"\\newcommand{{\\NGEN}}{{{n_gen}}}\n"
        f"\\newcommand{{\\NHAND}}{{{len(recs) - n_gen}}}\n"
        f"\\newcommand{{\\COVMED}}{{{coverage_median(covs):.2f}}}\n"
        f"\\newcommand{{\\GENPAIRS}}{{{len(gpairs)} pairs: {lvdist(gpairs)}}}\n"
        f"\\newcommand{{\\SAMECKPT}}{{{len(same)} pairs: {lvdist(same)}}}\n"
        f"\\newcommand{{\\NRZERO}}{{{sum(v['level'] == 0 for v in pairs.values())}}}\n"
        f"\\newcommand{{\\RZEROCLASSES}}{{{'; '.join(str(len(c)) for c in cls.values() if len(c) > 1)}}}\n"
        f"\\newcommand{{\\DEDUPN}}{{{len(reps)}}}\n"
        f"\\newcommand{{\\DEDUPALL}}{{{len(dpairs)} pairs: {lvdist(dpairs)}}}\n"
        f"\\newcommand{{\\DEDUPSAME}}{{{len(dsame)} pairs: {lvdist(dsame)}}}\n"
        "\\newcommand{\\PSIXENTRYROWS}{%\n" + "\n".join(rows) + "\n}\n"
    )
    summary = dict(
        schema_version="registry-numbers-v2-candidate",
        equivalence_policy="identical_normalized_signatures_including_unknown_states",
        all_classes=classes,
        representatives=sorted(reps),
        coverage_median=coverage_median(covs),
        n_stack=len(recs),
        n_pairs=len(pairs),
        levels={f"R{k}": lv[k] for k in range(6)},
        underspecified=und,
        backend_pair=dict(level=a["level"], coverage=a["coverage"]),
        dapo_pair=dict(level=b["level"], coverage=b["coverage"]),
        same_checkpoint=lvdist(same),
        generated=lvdist(gpairs),
        n_generated=n_gen,
        r0_classes=[c for c in cls.values() if len(c) > 1],
        dedup_all=lvdist(dpairs),
        dedup_same=lvdist(dsame),
    )
    summary["input_sha256"] = {
        str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted((q.HERE / "entries").glob("*.json"))
    }
    summary["analysis_sha256"] = hashlib.sha256(pathlib.Path(__file__).read_bytes()).hexdigest()
    summary["query_sha256"] = hashlib.sha256((q.HERE / "query.py").read_bytes()).hexdigest()
    summary["dependency_versions"] = {"python": platform.python_version()}
    summary["claim_receipts"] = [
        {
            "claim": key,
            "result_field": "/" + key,
            "analysis_version": summary["schema_version"],
            "input_hashes_ref": "/input_sha256",
            "evidence_level": "registry_metadata_recomputed_not_run_outcome_verification",
            "rounding": "counts exact; TeX coverage fractions two decimals",
        }
        for key in (
            "n_stack",
            "n_pairs",
            "coverage_median",
            "levels",
            "underspecified",
            "backend_pair",
            "dapo_pair",
            "n_generated",
            "dedup_all",
            "dedup_same",
        )
    ]
    (output_dir / "p6_registry_numbers_v2.json").write_text(json.dumps(summary, indent=1))
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=pathlib.Path, required=True)
    main(parser.parse_args().output_dir)
