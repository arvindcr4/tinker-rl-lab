"""Versioned, local-only analysis contracts introduced by Pro review 02.

No archived result is regenerated by importing this module. Undefined quantities
are serialized as null, never as evidence. Independent units must be declared by
the caller; seed uncertainty does not include evaluation-example uncertainty.
"""
from __future__ import annotations

import hashlib
import itertools
import json
import math
from collections import Counter
from pathlib import Path

import numpy as np
from scipy import stats

STATISTIC_VERSION = "pro-review-02-v2.1"


def finite_json(value):
    """Produce standards-compliant JSON data, retaining undefined values as null."""
    if isinstance(value, dict):
        return {str(k): finite_json(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, np.ndarray)):
        return [finite_json(v) for v in value]
    if isinstance(value, (float, np.floating)):
        return float(value) if math.isfinite(value) else None
    if isinstance(value, np.integer):
        return int(value)
    if isinstance(value, np.bool_):
        return bool(value)
    return value


def stable_seed(base, *parts):
    digest = hashlib.sha256(json.dumps([base, *parts], sort_keys=True).encode()).digest()
    return int.from_bytes(digest[:4], "big")


def structured_result(estimand, estimate=None, ci_low=None, ci_high=None,
                      unit="accuracy", method="unavailable", status="insufficient_data", **extra):
    return finite_json(dict(estimand=estimand, estimate=estimate, ci_low=ci_low,
                           ci_high=ci_high, unit=unit, method=method, status=status,
                           statistic_version=STATISTIC_VERSION, **extra))


def retention_noninferiority(a, b, threshold=.976, alpha=.05):
    """Paired-seed t inference for E[A] - threshold E[B] > 0.

    This is noninferiority, not two-sided equivalence. Inputs must be matched
    independent experimental observations of accuracies, never simulated CIs.
    A one-sided 95% lower bound corresponds to a two-sided 90% interval.
    """
    a, b = np.asarray(a, float), np.asarray(b, float)
    if a.ndim != 1 or a.shape != b.shape or not np.isfinite(a).all() or not np.isfinite(b).all():
        raise ValueError("finite, one-dimensional matched observations required")
    if not 0 < threshold <= 1 or not 0 < alpha < .5:
        raise ValueError("invalid retention threshold or alpha")
    if np.any((a < 0) | (a > 1) | (b < 0) | (b > 1)):
        raise ValueError("accuracy observations must be in [0, 1]")
    d = a - threshold * b
    n = len(d)
    estimate = float(d.mean()) if n else None
    ratio = float(a.mean() / b.mean()) if n and b.mean() > 0 else None
    result = structured_result(f"E[A] - {threshold} E[B]", estimate, n_pairs=n,
                               retention_ratio=ratio, threshold=threshold,
                               uncertainty_source="matched independent training seeds; fixed evaluation set")
    if n < 2:
        return result
    se = float(d.std(ddof=1) / np.sqrt(n))
    half = float(stats.t.ppf(1-alpha, n-1)) * se
    lo, hi = estimate-half, estimate+half
    p = float(stats.t.sf(estimate / se, n-1)) if se else (0.0 if estimate > 0 else 1.0)
    status = "superior" if lo > 0 else ("inferior" if hi < 0 else "inconclusive")
    # 'superior' is relative to the prespecified retention boundary, not equality.
    result.update(ci_low=lo, ci_high=hi, confidence_level=1-2*alpha,
                  method="paired_t_noninferiority", status=status,
                  noninferior=bool(lo > 0), p_one_sided=p)
    return result


def paired_spearman_ci(x, y, n_boot=2000, seed=0):
    """Shared-index bootstrap for independent paired observations only."""
    x, y = np.asarray(x), np.asarray(y)
    if x.ndim != 1 or x.shape != y.shape:
        raise ValueError("matched vectors required")
    if len(x) < 3:
        return float("nan"), float("nan")
    rng = np.random.default_rng(seed)
    values = []
    for _ in range(n_boot):
        idx = rng.integers(len(x), size=len(x))
        rho = spearman_coefficient(x[idx], y[idx])
        if np.isfinite(rho):
            values.append(rho)
    return tuple(np.quantile(values, [.025, .975])) if values else (float("nan"),)*2


def sampled_pairs(n, requested=2000, seed=0):
    """Bounded unique unordered sample; works even for an empty corpus."""
    import random
    pairs = list(itertools.combinations(range(n), 2))
    return random.Random(seed).sample(pairs, min(requested, len(pairs)))


def cell_distance_spearman_ci(fingerprints, outcomes, n_boot=2000, seed=0):
    """Cell bootstrap, recomputing both distances with the SAME cell indices.

    Requires cells to be independent sampling units. This is a sensitivity
    interval for that assumption, not a seed/test-population generalization CI.
    """
    n = len(fingerprints)
    if n != len(outcomes):
        raise ValueError("one outcome per cell required")
    if n < 3:
        return float("nan"), float("nan")
    fp = np.asarray(fingerprints)
    out = np.asarray(outcomes, float)
    if fp.ndim != 2 or not np.isfinite(out).all():
        raise ValueError("rectangular fingerprints and finite outcomes required")
    i, j = np.triu_indices(n, 1)
    # A bootstrap cannot identify a correlation undefined in the observed data.
    observed_h = (fp[i] != fp[j]).sum(axis=1)
    observed_d = np.abs(out[i] - out[j])
    if not math.isfinite(spearman_coefficient(observed_h, observed_d)):
        return float('nan'), float('nan')
    rng = np.random.default_rng(seed)
    draws = []
    for _ in range(n_boot):
        idx = rng.integers(n, size=n)
        h = (fp[idx[i]] != fp[idx[j]]).sum(axis=1)
        d = np.abs(out[idx[i]] - out[idx[j]])
        if np.ptp(h) and np.ptp(d):
            draws.append(spearman_coefficient(h, d))
    return tuple(np.quantile(draws, [.025, .975])) if draws else (float("nan"),)*2


def profile_counts(profiles):
    counts = Counter(profiles)
    n = sum(counts.values())
    singletons = sum(v == 1 for v in counts.values())
    return dict(n_cells=n, n_distinct_profiles=len(counts), n_singleton_cells=singletons,
                singleton_fraction=singletons/n if n else None)


def result_provenance(paths, **spec):
    """Hashes of actual inputs; no claim that outputs have been revalidated."""
    import subprocess
    try:
        commit = subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        commit = None
    return dict(statistic_version=STATISTIC_VERSION, analysis_commit=commit,
                input_sha256={str(p): hashlib.sha256(Path(p).read_bytes()).hexdigest()
                              for p in paths if Path(p).is_file()}, **spec)


def exact_small_spearman(x, y):
    """Two-sided exact permutation test for n<=8 under exchangeable pairings.

    Larger inputs report the coefficient with no p-value instead of silently
    switching to asymptotic inference. Fixed experimental conditions require a
    separate justification of exchangeability before using this test.
    """
    x, y = np.asarray(x, float), np.asarray(y, float)
    if x.shape != y.shape or x.ndim != 1 or not np.isfinite(x).all() or not np.isfinite(y).all():
        raise ValueError('finite paired vectors required')
    if len(x) < 2 or np.ptp(x) == 0 or np.ptp(y) == 0:
        return float('nan'), float('nan')
    rho = float(stats.spearmanr(x, y).statistic)
    if len(x) > 8:
        return rho, float('nan')
    rx, ry = stats.rankdata(x), stats.rankdata(y)
    rx, ry = rx-rx.mean(), ry-ry.mean()
    denom = np.linalg.norm(rx)*np.linalg.norm(ry)
    exceed = sum(abs(np.dot(rx, permutation)/denom) >= abs(rho)-1e-12
                 for permutation in itertools.permutations(ry))
    return rho, exceed/math.factorial(len(x))


def profile_target_increment(population_size, baseline_profiles):
    """Additional distinct profiles required to reach at least half the cells."""
    if not 0 <= baseline_profiles <= population_size:
        raise ValueError("baseline must be within the population")
    return max(0, math.ceil(population_size / 2) - baseline_profiles)


def spearman_coefficient(x, y):
    """Tie-corrected Spearman point; constant or inadequate data is undefined."""
    x, y = np.asarray(x, float), np.asarray(y, float)
    if x.ndim != 1 or x.shape != y.shape:
        raise ValueError("matched vectors required")
    if len(x) < 2 or not np.isfinite(x).all() or not np.isfinite(y).all() or not np.ptp(x) or not np.ptp(y):
        return float("nan")
    return float(stats.spearmanr(x, y).statistic)
