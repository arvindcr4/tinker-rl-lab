#!/usr/bin/env python3
"""Regenerate every registry number quoted in P6 (Deep Review 2026-10-18).

Same computation as platform_hybrid/analysis_publication_fixes/p6_registry_numbers.py,
calling platform_hybrid/registry/query.py, with one change required by the review
protocol (rule 2, unsourced data removed): the 11 ``zvf130_*`` stack records are
excluded. They were written from zvf_iter130_method_risk.tsv, whose variance-
mitigation rows are a declared simulation projection and whose tool-use rows are
anchors fixed by platform_modal/scripts/zvf_diagnostic_iter130.py; no training run
stands behind them.

Writes  platform_hybrid/experiments/results/review_2026-10-18/P6_registry/p6_registry_generated_proposed.tex (proposed replacement for paper/sections/p6_registry_generated.tex)
        platform_hybrid/experiments/results/review_2026-10-18/P6_registry/p6_registry_numbers.json
"""

import collections, hashlib, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
PH = ROOT / "platform_hybrid"
sys.path.insert(0, str(PH / "registry"))
import query as q

sys.path.insert(0, str(PH / "analysis_publication_fixes"))
from analysis_validation import equivalence_classes, coverage_median

EXCLUDE_PREFIX = "zvf130_"
ALL = q.load("stack")
recs = {k: v for k, v in ALL.items() if not k.startswith(EXCLUDE_PREFIX)}
excluded = sorted(set(ALL) - set(recs))


def family(rid):
    if rid.startswith("colab-open_"):
        return "B"
    if rid.startswith("wandb_"):
        return "W"
    if rid.endswith("qwen3-8b_gsm8k"):
        return "A"
    if any(rid.startswith(f"tinker_{m}_qwen3.5") for m in ("aero", "gift", "areal")):
        return "D"
    if rid.startswith("tinker_") and "qwen3.5-4b" in rid:
        return "C"
    raise ValueError(rid)


def exec_mode(r):
    rc = r.get("run_config") or {}
    mode = (rc.get("execution.mode") or {}).get("value")
    if mode == "dryrun":
        return "dry-run"
    n = len(r.get("seeds") or [])
    return (
        ("toy run" if family(r["id"]) == "B" else "run") + f", {n} seed" + ("s" if n != 1 else "")
    )


def ckpt(r):
    v = q.field_view(r)["checkpoint.id"]
    return q._key("checkpoint.id", v["value"]) if q.is_known(v) else None


def lvdist(ps):
    c = collections.Counter(r["level"] for r in ps.values())
    return ", ".join(f"R{k} {c[k]}" for k in range(6) if c[k])


pairs = q.all_pairs(recs)
lv = collections.Counter(r["level"] for r in pairs.values())
und = sum(r["underspecified"] for r in pairs.values())
dist = ", ".join(f"R{k}: {lv[k]}" for k in range(6))
same = {k: v for k, v in pairs.items() if ckpt(recs[k[0]]) and ckpt(recs[k[0]]) == ckpt(recs[k[1]])}
classes = equivalence_classes(recs, q)
reps = {m[0]: recs[m[0]] for m in classes}
dpairs = q.all_pairs(reps)
dsame = {
    k: v for k, v in dpairs.items() if ckpt(reps[k[0]]) and ckpt(reps[k[0]]) == ckpt(reps[k[1]])
}
gen = {k: r for k, r in recs.items() if r.get("run_config")}
gpairs = q.all_pairs(gen)
covs = sorted(r["coverage"] for r in pairs.values())
a = q.stackdiff(recs["trl_grpo_qwen3-8b_gsm8k"], recs["tinker_grpo_qwen3-8b_gsm8k"])
b = q.stackdiff(recs["colab-open_dapo_e3"], recs["tinker_dapo_qwen3.5-4b_gsm8k"])
ckpts = sorted({ckpt(r) for r in recs.values() if ckpt(r)})
n_unknown_ckpt = sum(ckpt(r) is None for r in recs.values())

# reference_kl census (query --item reference_kl), all retained stack records
kl = collections.Counter()
for r in recs.values():
    s = q.item_score(r["min_report"]["reference_kl"], "reference_kl")
    kl["FULL" if s == 1.0 else ("PARTIAL" if s > 0 else "UNREPORTED")] += 1

# per-item leaf denominators used by the badge (schema leaves minus source/description)
defs = json.loads((PH / "registry/schema.json").read_text())["$defs"]["min_report"]["properties"]
leaves = {it: sorted(set(defs[it]["properties"]) - {"source", "description"}) for it in q.ITEMS}

ci_ids = sorted(
    k for k, r in recs.items() if (r.get("outcomes") or {}).get("ci_method") is not None
)

badges = {k: q.badge(r)[0] for k, r in recs.items()}
fam = collections.defaultdict(list)
for k in recs:
    fam[family(k)].append(k)


def rng(ids):
    v = sorted(badges[i] for i in ids)
    return f"{v[0]}" if v[0] == v[-1] else f"{v[0]}--{v[-1]}"


def esc(s):
    return str(s).replace("_", r"\_")


rows = []
for rid in sorted(recs):
    r = recs[rid]
    mz = (r.get("outcomes") or {}).get("mean_zvf")
    model = (
        r.get("model") or (r.get("run_config") or {}).get("checkpoint.id", {}).get("value") or "--"
    )
    rows.append(
        f"{esc(rid)} & {esc(r['label_claimed'])} & {esc(r['framework']['openness'])} & "
        f"{esc(str(model).split('/')[-1])} & {exec_mode(r)} & {'--' if mz is None else f'{mz:.3f}'} & "
        f"{badges[rid]} & {q.spec_coverage(r):.2f} \\\\"
    )

tex = [
    "% GENERATED by tools/review_ledger/P6_registry_numbers.py -- do not edit",
    "% zvf130_* fixture records excluded (simulation-projection source; Deep Review 2026-10-18)",
]
macros = dict(
    STACKDIFFNPAIRS=len(pairs),
    STACKDIFFDIST=dist,
    STACKDIFFUNDER=f"{und}/{len(pairs)}",
    STACKDIFFCOVA=f"{a['coverage']:.2f}",
    STACKDIFFCOVB=f"{b['coverage']:.2f}",
    NSTACK=len(recs),
    NSTACKALL=len(ALL),
    NFIXTURE=len(excluded),
    NFIELDS=len(q.FIELDS),
    NGEN=len(gen),
    NHAND=len(recs) - len(gen),
    COVMED=f"{coverage_median(covs):.2f}",
    GENPAIRS=f"{len(gpairs)} pairs: {lvdist(gpairs)}",
    SAMECKPT=f"{len(same)} pairs: {lvdist(same)}",
    NRZERO=lv[0],
    DEDUPN=len(reps),
    DEDUPALL=f"{len(dpairs)} pairs: {lvdist(dpairs)}",
    DEDUPSAME=f"{len(dsame)} pairs: {lvdist(dsame)}",
    NCKPT=len(ckpts),
    KLFULL=kl["FULL"],
    KLPARTIAL=kl["PARTIAL"],
    KLUNREP=kl["UNREPORTED"],
    NCIMETHOD=len(ci_ids),
    LEAFCOUNTS=", ".join(f"{len(leaves[i])}" for i in q.ITEMS),
    NLEAVES=sum(len(v) for v in leaves.values()),
    BADGEA=rng(fam["A"]),
    BADGEB=rng(fam["B"]),
    BADGEC=rng(fam["C"]),
    BADGED=rng(fam["D"]),
    BADGEW=rng(fam["W"]),
    BADGEALL=rng(list(recs)),
)
for k, v in macros.items():
    tex.append(f"\\newcommand{{\\{k}}}{{{v}}}")
tex.append("\\newcommand{\\PSIXENTRYROWS}{%\n" + "\n".join(rows) + "\n}")
(
    PH / "experiments/results/review_2026-10-18/P6_registry/p6_registry_generated_proposed.tex"
).write_text("\n".join(tex) + "\n")

out = PH / "experiments/results/review_2026-10-18/P6_registry"
out.mkdir(parents=True, exist_ok=True)
summary = dict(
    macros=macros,
    excluded=excluded,
    checkpoints=ckpts,
    n_unknown_checkpoint=n_unknown_ckpt,
    leaves=leaves,
    ci_method_ids=ci_ids,
    kl_census=dict(kl),
    families={k: sorted(v) for k, v in fam.items()},
    r0_classes=[c for c in classes if len(c) > 1],
    input_sha256={
        p.name: hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted((PH / "registry/entries").glob("*.json"))
    },
    query_sha256=hashlib.sha256((PH / "registry/query.py").read_bytes()).hexdigest(),
)
(out / "p6_registry_numbers.json").write_text(json.dumps(summary, indent=1))
print(
    json.dumps(
        {
            k: summary[k]
            for k in (
                "macros",
                "checkpoints",
                "n_unknown_checkpoint",
                "ci_method_ids",
                "kl_census",
                "r0_classes",
            )
        },
        indent=1,
    )
)
